-- Comparison Operators
-- Equal to  
SELECT * FROM students
WHERE s_name='Nandu';

-- Not Equal to
SELECT * FROM students
WHERE s_id != 4;

-- Greater Than
SELECT * FROM students
WHERE s_id > 8;

-- Greater Than or Equal to
SELECT * FROM students
WHERE s_id >= 8;

-- Lesser Than
SELECT * FROM students
WHERE s_id < 3;

-- Lesser Than or Equal to
SELECT * FROM students
WHERE s_id <= 3;